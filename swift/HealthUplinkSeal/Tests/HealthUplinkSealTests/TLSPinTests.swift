    /// against CryptoKit's own SubjectPublicKeyInfo encoding. Not a known-value check; `testVectorPin` is one.
    func testPinIsSHA256OfHeaderPlusKey() throws {
        let key = P256.Signing.PrivateKey()
        let spki = key.publicKey.derRepresentation          // CryptoKit's DER is SubjectPublicKeyInfo
        XCTAssertEqual(TLSPin.p256SPKIHeader + key.publicKey.x963Representation, spki)
        XCTAssertEqual(TLSPin.spkiSHA256(p256Uncompressed: key.publicKey.x963Representation),
                       Data(SHA256.hash(data: spki)).base64EncodedString())
    }

