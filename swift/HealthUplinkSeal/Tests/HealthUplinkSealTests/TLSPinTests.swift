    private func trust(_ base64: String) throws -> SecTrust {
        try trust(der: try XCTUnwrap(Data(base64Encoded: base64, options: .ignoreUnknownCharacters)))
    }

    private func trust(der: Data) throws -> SecTrust {
        let cert = try XCTUnwrap(SecCertificateCreateWithData(nil, der as CFData))
        var trust: SecTrust?
        XCTAssertEqual(SecTrustCreateWithCertificates(cert, SecPolicyCreateBasicX509(), &trust), errSecSuccess)
        return try XCTUnwrap(trust)
    }

    /// Known-value check against the shared vector: the leaf pin, the pin from the raw point, and the SPKI layout.
    func testVectorPin() throws {
        let v = try Vectors.load("tls-v1.json")
        let pin = v.str("tls_sha256")
        XCTAssertEqual(TLSPin.spkiSHA256(leafOf: try trust(der: v.base64("cert_der"))), pin)
        XCTAssertEqual(TLSPin.spkiSHA256(p256Uncompressed: v.base64("p256_uncompressed")), pin)
        XCTAssertEqual(TLSPin.p256SPKIHeader + v.base64("p256_uncompressed"), v.base64("spki_der"))
        XCTAssertEqual(Data(SHA256.hash(data: v.base64("spki_der"))).base64EncodedString(), pin)
    }

    func testOnlyP256LeafHasPin() throws {
        XCTAssertNil(TLSPin.spkiSHA256(leafOf: try trust(Self.p384Cert)))
        XCTAssertNil(TLSPin.spkiSHA256(leafOf: try trust(Self.rsaCert)))
    }

    /// The certificate is self-signed and its name is not checked, so a match rests on the pin alone.
    func testMatchesComparesThePinOnly() throws {
        let v = try Vectors.load("tls-v1.json")
        let pin = v.str("tls_sha256")
        let t = try trust(der: v.base64("cert_der"))
        XCTAssertTrue(TLSPin.matches(t, pin: pin))
        var flipped = Array(pin)
        flipped[0] = flipped[0] == "A" ? "B" : "A"
        XCTAssertFalse(TLSPin.matches(t, pin: String(flipped)))
        XCTAssertFalse(TLSPin.matches(t, pin: String(pin.dropLast())))
        XCTAssertFalse(TLSPin.matches(t, pin: ""))
        XCTAssertFalse(TLSPin.matches(try trust(Self.rsaCert), pin: "O7EtlPojqCnbwY6B8XnQ+/GK0qwPREJBbhRax/p/keQ="))
    }
