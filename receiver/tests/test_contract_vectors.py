"""Checks contract/vectors/tls-v1.json and pairing-v1.json (contract section 2).

Both files are generated by tests/make_vectors.py and read by the receiver and the iPhone app.
"""

import base64
import hashlib
import json
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

import make_vectors

VECTORS = Path(__file__).resolve().parents[2] / "contract" / "vectors"

# DER prefix of an ECDSA P-256 SubjectPublicKeyInfo; the uncompressed point follows it (TLSPin.p256SPKIHeader).
P256_SPKI_HEADER = bytes.fromhex("3059301306072a8648ce3d020106082a8648ce3d030107034200")

EXPECT_VALUES = {
    "ok",
    "bad_payload",
    "unsupported_version",
    "unsupported_mode",
    "tailnet_name",
    "needs_https",
    "bad_pin",
    "pin_needs_local_host",
}


def _load(name: str) -> dict:
    return json.loads((VECTORS / name).read_text())


def test_vector_files_match_generator():
    assert _load("tls-v1.json") == make_vectors.build_tls(), "tls-v1.json drifted; rerun tests/make_vectors.py"
    assert _load("pairing-v1.json") == make_vectors.build_pairing(), "pairing-v1.json drifted; rerun tests/make_vectors.py"


def test_tls_vector_pin_matches_cert():
    v = _load("tls-v1.json")
    cert = x509.load_der_x509_certificate(base64.b64decode(v["cert_der"], validate=True))
    key = cert.public_key()
    assert isinstance(key, ec.EllipticCurvePublicKey) and key.curve.name == "secp256r1"

    spki = key.public_bytes(Encoding.DER, PublicFormat.SubjectPublicKeyInfo)
    point = base64.b64decode(v["p256_uncompressed"], validate=True)
    assert len(point) == 65 and point[0] == 0x04
    assert base64.b64decode(v["spki_der"], validate=True) == spki == P256_SPKI_HEADER + point

    pin = base64.b64decode(v["tls_sha256"], validate=True)
    assert len(pin) == 32
    assert pin == hashlib.sha256(spki).digest()
    # The certificate is self-signed with the same key.
    cert.verify_directly_issued_by(cert)


def test_pairing_cases_are_complete():
    cases = _load("pairing-v1.json")["cases"]
    assert {c["expect"] for c in cases} == EXPECT_VALUES
    names = [c["name"] for c in cases]
    assert len(names) == len(set(names)), "case names must be unique"


def test_pairing_case_fields_match_payload():
    for c in _load("pairing-v1.json")["cases"]:
        assert isinstance(c["payload"], str), c["name"]
        payload = json.loads(c["payload"])
        assert c["url"] == payload["url"], c["name"]
        # Absent and null are the same here: no pin.
        assert c["tls_sha256"] == payload.get("tls_sha256"), c["name"]
        if "tls_sha256" in payload:
            assert payload["tls_sha256"] is not None, f"{c['name']}: write no field rather than null"


def test_valid_pin_cases_use_the_tls_vector():
    pin = _load("tls-v1.json")["tls_sha256"]
    cases = _load("pairing-v1.json")["cases"]
    pinned = [c for c in cases if c["expect"] in ("ok", "needs_https", "pin_needs_local_host") and c["tls_sha256"] is not None]
    assert pinned and all(c["tls_sha256"] == pin for c in pinned)


def test_required_cases_present():
    """The cases both the receiver and the app must agree on, including which error wins when several apply."""
    pin = _load("tls-v1.json")["tls_sha256"]
    got = {(c["url"], c["tls_sha256"] is not None, c["expect"]) for c in _load("pairing-v1.json")["cases"] if c["tls_sha256"] in (None, pin)}
    want = {
        ("http://100.100.1.1:8796", False, "ok"),
        ("http://100.64.0.1", False, "ok"),
        ("http://100.128.0.1", False, "needs_https"),
        ("http://192.168.1.10:8796", False, "needs_https"),
        ("http://mac.local:8796", False, "needs_https"),
        ("https://mac.local:8796", True, "ok"),
        ("https://192.168.1.10:8796", True, "ok"),
        ("https://100.100.1.1:8796", True, "ok"),
        ("https://192.168.1.10:8796", False, "ok"),
        ("https://health.example.com", False, "ok"),
        ("https://health.example.com", True, "pin_needs_local_host"),
        ("http://100.100.1.1:8796", True, "needs_https"),
        ("https://x.tail1234.ts.net", False, "tailnet_name"),
        ("http://x.tail1234.ts.net", False, "tailnet_name"),
        ("http://0100.100.1.1", False, "needs_https"),
        ("https://mac:8796", True, "ok"),
        ("http://mac:8796", False, "needs_https"),
        ("http://[fd7a:115c:a1e0::1]:8796", False, "needs_https"),
        ("https://[fd00::10]:8796", True, "pin_needs_local_host"),
    }
    assert want <= got, want - got
    expects = {c["expect"] for c in _load("pairing-v1.json")["cases"] if c["tls_sha256"] is not None and c["tls_sha256"] != pin}
    assert expects == {"bad_pin"}
